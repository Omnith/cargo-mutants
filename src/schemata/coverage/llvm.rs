//! Interface to the LLVM coverage tools, `llvm-profdata` and `llvm-cov`, and
//! parsing of their output.

#![warn(clippy::pedantic)]

use std::ffi::OsString;

use camino::{Utf8Path, Utf8PathBuf};
use serde::Deserialize;

use crate::span::{LineColumn, Span};

/// Region kind of ordinary code in `llvm-cov export` output; other kinds are
/// expansions, skipped (unreachable) code, gaps, and branches.
const CODE_REGION_KIND: u64 = 0;

/// Add the flag that instruments a crate for coverage to a rustc command line,
/// if it compiles a crate rather than querying rustc.
pub(crate) fn instrumented_rustc_args(mut args: Vec<OsString>) -> Vec<OsString> {
    let compiles = args.iter().any(|arg| arg == "--crate-name")
        && !args
            .iter()
            .any(|arg| arg.to_string_lossy().starts_with("--print"));
    if compiles {
        args.extend(["-C".into(), "instrument-coverage".into()]);
    }
    args
}

/// The names of the functions that ran, from a profile in `llvm-profdata merge
/// --text` format: those with any nonzero counter.
pub(crate) fn executed_functions(profile_text: &str) -> Vec<&str> {
    // Each function is a paragraph: its name, then "# Func Hash:", the hash,
    // "# Num Counters:", the count, "# Counter Values:", and one value per line.
    // Header lines before the first function start with `#` or `:`.
    let mut executed = Vec::new();
    for paragraph in profile_text.split("\n\n") {
        let mut lines = paragraph
            .lines()
            .map(str::trim)
            .filter(|line| !line.is_empty() && !line.starts_with(':'))
            .skip_while(|line| line.starts_with('#'));
        let Some(name) = lines.next() else {
            continue;
        };
        let ran = lines
            .skip_while(|line| *line != "# Counter Values:")
            .skip(1)
            .any(|value| value.parse::<u64>().is_ok_and(|count| count > 0));
        if ran {
            executed.push(name);
        }
    }
    executed
}

/// An instrumented function and the source regions of its code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct MappedFunction {
    /// Mangled name, as in profiles.
    pub name: String,
    /// Code regions, in files relative to the tree root.
    pub regions: Vec<(Utf8PathBuf, Span)>,
}

/// Parse `llvm-cov export -format=text` output into the functions it maps, keeping
/// only code regions in files under one of `roots`, with paths made relative to it.
///
/// Every function is returned, even with no regions under the roots, like a closure
/// generated by a dependency's macro, so that running it is known to run no code in
/// the tree.
pub(crate) fn mapped_functions(
    export_json: &str,
    roots: &[Utf8PathBuf],
) -> serde_json::Result<Vec<MappedFunction>> {
    let export: Export = serde_json::from_str(export_json)?;
    let relative = |path: &str| {
        roots
            .iter()
            .find_map(|root| Utf8Path::new(path).strip_prefix(root).ok())
            .map(Utf8Path::to_owned)
    };
    Ok(export
        .data
        .into_iter()
        .flat_map(|data| data.functions)
        .map(|function| {
            let regions: Vec<(Utf8PathBuf, Span)> = function
                .regions
                .iter()
                .filter_map(|region| {
                    // [line_start, column_start, line_end, column_end, count, file_id,
                    // expanded_file_id, kind]
                    let &[
                        line_start,
                        column_start,
                        line_end,
                        column_end,
                        _,
                        file_id,
                        _,
                        kind,
                        ..,
                    ] = region.as_slice()
                    else {
                        return None;
                    };
                    if kind != CODE_REGION_KIND {
                        return None;
                    }
                    let file = relative(function.filenames.get(usize::try_from(file_id).ok()?)?)?;
                    let position = |line: u64, column: u64| -> Option<LineColumn> {
                        Some(LineColumn {
                            line: usize::try_from(line).ok()?,
                            column: usize::try_from(column).ok()?,
                        })
                    };
                    Some((
                        file,
                        Span {
                            start: position(line_start, column_start)?,
                            end: position(line_end, column_end)?,
                        },
                    ))
                })
                .collect();
            MappedFunction {
                name: function.name,
                regions,
            }
        })
        .collect())
}

/// The parts of `llvm-cov export -format=text` output that are used.
#[derive(Deserialize)]
struct Export {
    data: Vec<ExportData>,
}

#[derive(Deserialize)]
struct ExportData {
    functions: Vec<ExportFunction>,
}

#[derive(Deserialize)]
struct ExportFunction {
    name: String,
    filenames: Vec<String>,
    regions: Vec<Vec<u64>>,
}

#[cfg(test)]
mod test {
    use indoc::indoc;
    use pretty_assertions::assert_eq;

    use super::*;

    fn os_args(args: &[&str]) -> Vec<OsString> {
        args.iter().map(OsString::from).collect()
    }

    #[test]
    fn instrumented_rustc_args_instruments_crate_compilations_only() {
        assert_eq!(
            instrumented_rustc_args(os_args(&["rustc", "--crate-name", "foo", "src/lib.rs"])),
            os_args(&[
                "rustc",
                "--crate-name",
                "foo",
                "src/lib.rs",
                "-C",
                "instrument-coverage"
            ])
        );
        for query in [
            ["rustc", "-vV"].as_slice(),
            &["rustc", "-", "--crate-name", "___", "--print=file-names"],
        ] {
            assert_eq!(instrumented_rustc_args(os_args(query)), os_args(query));
        }
    }

    #[test]
    fn executed_functions_lists_functions_with_nonzero_counters() {
        let text = indoc! {"
            # IR level Instrumentation Flag
            :fe
            _RNvCs1_3foo3ran
            # Func Hash:
            1234
            # Num Counters:
            2
            # Counter Values:
            0
            3

            _RNvCs1_3foo8not_ran
            # Func Hash:
            99
            # Num Counters:
            1
            # Counter Values:
            0

            src/lib.rs;_RNvCs1_3foo5local
            # Func Hash:
            7
            # Num Counters:
            1
            # Counter Values:
            1
        "};
        assert_eq!(
            executed_functions(text),
            ["_RNvCs1_3foo3ran", "src/lib.rs;_RNvCs1_3foo5local"]
        );
        assert!(executed_functions("").is_empty());
    }

    #[test]
    fn mapped_functions_keeps_code_regions_under_the_roots_and_every_function() {
        let json = r#"{"type": "llvm.coverage.json.export", "version": "3.0.1",
            "data": [{"files": [], "totals": {}, "functions": [
                {"name": "_RNvCs1_3foo3add", "count": 1,
                 "filenames": ["/private/ws/src/lib.rs", "/home/me/.cargo/registry/dep/src/lib.rs"],
                 "regions": [
                    [3, 1, 3, 30, 1, 0, 0, 0],
                    [4, 5, 4, 10, 0, 0, 0, 2],
                    [5, 9, 6, 2, 0, 1, 0, 0]
                 ]},
                {"name": "_RNvCs1_3bar4main", "count": 0,
                 "filenames": ["/ws/src/bin/bar.rs"],
                 "regions": [[1, 1, 2, 2, 0, 0, 0, 0]]},
                {"name": "_RNCNvCs1_3foo4race0s_0B3_", "count": 1,
                 "filenames": ["/home/me/.cargo/registry/tokio/src/macros/select.rs"],
                 "regions": [[10, 1, 12, 2, 1, 0, 0, 0]]}
            ]}]}"#;
        let roots = ["/ws".into(), "/private/ws".into()];
        assert_eq!(
            mapped_functions(json, &roots).unwrap(),
            [
                MappedFunction {
                    name: "_RNvCs1_3foo3add".to_owned(),
                    regions: vec![("src/lib.rs".into(), Span::quad(3, 1, 3, 30))],
                },
                MappedFunction {
                    name: "_RNvCs1_3bar4main".to_owned(),
                    regions: vec![("src/bin/bar.rs".into(), Span::quad(1, 1, 2, 2))],
                },
                // Code generated by a dependency's macro, like `tokio::select!`, is in
                // the dependency's source, but the function is still known.
                MappedFunction {
                    name: "_RNCNvCs1_3foo4race0s_0B3_".to_owned(),
                    regions: vec![],
                },
            ]
        );
    }
}
